// Builds supabase/seed.sql from src/lib/demo-data.json.
// The seed runs only on a LOCAL database (`supabase db reset`), never in production.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const data = JSON.parse(readFileSync(new URL("../src/lib/demo-data.json", import.meta.url), "utf8"));
const q = (v) =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;
const uid = (s) => {
  const h = createHash("sha1").update(s).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const lines = [
  "-- Generated by scripts/generate-seed.mjs. Demo content for local development only.",
  "select set_config('smoch.internal', 'on', false);",
  "",
];

const authors = [...new Set(data.reviews.map((r) => r.authorName))];
for (const [i, name] of authors.entries()) {
  const id = uid(`author:${name}`);
  lines.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at) values ('00000000-0000-0000-0000-000000000000', ${q(id)}, 'authenticated', 'authenticated', ${q(`demo${i + 1}@example.com`)}, '', now(), '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: name }))}, now(), now());`,
    `update public.profiles set display_name = ${q(name)} where id = ${q(id)};`,
  );
}
lines.push("");

for (const c of data.companies) {
  lines.push(
    `insert into public.companies (id, slug, name, category, tagline, about, website, registry_id, registry_verified, city, founded, price_range, claimed, status) values (${[
      c.id,
      c.slug,
      c.name,
      c.category,
      c.tagline,
      c.about,
      c.website,
      c.registryId,
      c.registryVerified,
      c.city,
      c.founded,
      c.priceRange,
      c.claimed,
      "published",
    ]
      .map(q)
      .join(", ")});`,
  );
}
lines.push("");

for (const r of data.reviews) {
  lines.push(
    `insert into public.reviews (id, company_id, user_id, author_name, rating, body, paid, amount_paid, verified_purchase, status, created_at) values (${[
      r.id,
      r.companyId,
      uid(`author:${r.authorName}`),
      r.authorName,
      r.rating,
      r.body,
      r.paid,
      r.amountPaid,
      r.verifiedPurchase,
      "published",
      r.createdAt,
    ]
      .map(q)
      .join(", ")});`,
  );
  if (r.reply) {
    lines.push(
      `insert into public.review_replies (review_id, company_id, body, created_at) values (${[r.id, r.companyId, r.reply.body, r.reply.createdAt].map(q).join(", ")});`,
    );
  }
}

// Short extra reviews so some demo companies cross the 10-rating threshold
// and show a score, while others stay below it.
const shortBodies = {
  5: "ממליץ בחום, קיבלתי מה שהובטח.",
  4: "טוב מאוד, עם כמה דברים לשפר.",
  3: "בסדר, לא יותר מזה.",
  2: "פחות ממה שציפיתי.",
  1: "לא ממליץ, חבל על הכסף.",
};
const extraRatings = {
  "green-candle": [5, 5, 4, 5, 4, 5, 3, 5, 4],
  "signal-bot-pro": [1, 1, 2, 1, 1, 5, 1, 1],
};
let extra = 0;
for (const [slug, ratings] of Object.entries(extraRatings)) {
  const company = data.companies.find((c) => c.slug === slug);
  for (const [i, rating] of ratings.entries()) {
    const id = uid(`rater:${slug}:${i}`);
    const name = `מדרג/ת ${i + 1}`;
    lines.push(
      `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at) values ('00000000-0000-0000-0000-000000000000', ${q(id)}, 'authenticated', 'authenticated', ${q(`rater-${slug}-${i}@example.com`)}, '', now(), '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: name }))}, now(), now());`,
      `insert into public.reviews (company_id, user_id, author_name, rating, body, status) values (${[company.id, id, name, rating, shortBodies[rating], "published"].map(q).join(", ")});`,
    );
    extra++;
  }
}

lines.push("", "select set_config('smoch.internal', 'off', false);", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(
  `seed.sql: ${authors.length + extra} users, ${data.companies.length} companies, ${data.reviews.length} reviews + ${extra} short reviews`,
);
